uint8_t SHT30_Read_TempHum(float *temp, float *hum)
{
    // 0x2C, 0x06 ?????? SHT30 ???? (????,??????)
    uint8_t cmd[2] = {0x2C, 0x06};
    uint8_t rx_data[6];
    uint16_t raw_temp, raw_hum;

    // 1. ??????
    if (HAL_I2C_Master_Transmit(&hi2c1, SHT30_I2C_ADDR, cmd, 2, HAL_MAX_DELAY) != HAL_OK) {
        return 0; // ????
    }

    // 2. ????????? (??????????? 15ms,??? 20ms)
    HAL_Delay(20);

    // 3. ?? 6 ??????
    // ??: [Temp MSB] [Temp LSB] [Temp CRC] [Hum MSB] [Hum LSB] [Hum CRC]
    if (HAL_I2C_Master_Receive(&hi2c1, SHT30_I2C_ADDR, rx_data, 6, HAL_MAX_DELAY) != HAL_OK) {
        return 0; // ????
    }

    // ?????????,???????? CRC ??,??????????
    raw_temp = (rx_data[0] << 8) | rx_data[1];
    raw_hum = (rx_data[3] << 8) | rx_data[4];

    // 4. ?? SHT30 ??????????
    *temp = -45.0f + (175.0f * (float)raw_temp / 65535.0f);
    *hum = 100.0f * (float)raw_hum / 65535.0f;

    return 1; // ??
}